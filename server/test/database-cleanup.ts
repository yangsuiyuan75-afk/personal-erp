import type { PrismaClient } from '@prisma/client'

export async function cleanDatabase(prisma: PrismaClient): Promise<void> {
  await prisma.salesChannel.updateMany({ data: { defaultLocationId: null } })
  await prisma.$transaction([
    prisma.auditLog.deleteMany(),
    prisma.refreshSession.deleteMany(),
    prisma.systemSetting.deleteMany(),
    prisma.backupHistory.deleteMany(),
    prisma.fileAssociation.deleteMany(),
    prisma.productImage.deleteMany(),
    prisma.fileAsset.deleteMany(),
    prisma.paymentAllocation.deleteMany(),
    prisma.receiptAllocation.deleteMany(),
    prisma.payment.deleteMany(),
    prisma.receipt.deleteMany(),
    prisma.accountAdjustment.deleteMany(),
    prisma.financialTransaction.deleteMany(),
    prisma.financialAccount.deleteMany(),
    prisma.inventoryBatchAllocation.deleteMany(),
    prisma.qualityInventoryMovement.deleteMany(),
    prisma.supplierCompensationReceivable.deleteMany(),
    prisma.supplierCredit.deleteMany(),
    prisma.supplierClaimSettlement.deleteMany(),
    prisma.supplierClaimItem.deleteMany(),
    prisma.supplierClaim.deleteMany(),
    prisma.qualityIssue.deleteMany(),
    prisma.qualityInspectionItem.deleteMany(),
    prisma.qualityInspection.deleteMany(),
    prisma.salesReturnBatchTrace.deleteMany(),
    prisma.customerRefund.deleteMany(),
    prisma.salesReturnItem.deleteMany(),
    prisma.salesReturn.deleteMany(),
    prisma.salesIssueItem.deleteMany(),
    prisma.salesIssue.deleteMany(),
    prisma.receivableAdjustment.deleteMany(),
    prisma.receivable.deleteMany(),
    prisma.salesOrderItem.deleteMany(),
    prisma.salesOrder.deleteMany(),
    prisma.salesPrice.deleteMany(),
    prisma.inventoryTransactionLine.deleteMany(),
    prisma.inventoryTransaction.deleteMany(),
    prisma.inventoryBatch.deleteMany(),
    prisma.purchaseReturnItem.deleteMany(),
    prisma.purchaseReturn.deleteMany(),
    prisma.purchaseReceiptItem.deleteMany(),
    prisma.purchaseReceipt.deleteMany(),
    prisma.payableAdjustment.deleteMany(),
    prisma.payable.deleteMany(),
    prisma.purchaseOrderItem.deleteMany(),
    prisma.purchaseOrder.deleteMany(),
    prisma.purchasePrice.deleteMany(),
    prisma.channelAllocationItem.deleteMany(),
    prisma.channelAllocation.deleteMany(),
    prisma.inventoryOpeningItem.deleteMany(),
    prisma.inventoryOpening.deleteMany(),
    prisma.inventoryAdjustmentItem.deleteMany(),
    prisma.inventoryAdjustment.deleteMany(),
    prisma.inventoryTransferItem.deleteMany(),
    prisma.inventoryTransfer.deleteMany(),
    prisma.inventoryBalance.deleteMany(),
    prisma.idempotencyRecord.deleteMany(),
    prisma.sku.deleteMany(),
    prisma.product.deleteMany(),
    prisma.category.deleteMany(),
    prisma.unit.deleteMany(),
    prisma.supplier.deleteMany(),
    prisma.buyer.deleteMany(),
    prisma.purchaseChannel.deleteMany(),
    prisma.customer.deleteMany(),
    prisma.inventoryLocation.deleteMany(),
    prisma.salesChannel.deleteMany(),
    prisma.adminUser.deleteMany(),
  ])
}
